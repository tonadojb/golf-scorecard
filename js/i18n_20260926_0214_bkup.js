function t(key){
  var dict = I18N[(state && state.lang) || 'ko'];
  var v = dict[key];
  if(typeof v === 'function'){
    var args = Array.prototype.slice.call(arguments, 1);
    return v.apply(null, args);
  }
  return v;
}


